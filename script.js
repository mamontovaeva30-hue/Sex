function openPage(pageName) {
    const pages = $$(".page");

    pages.forEach(page => {
        page.classList.remove("active");
    });

    const target = $("#page-" + pageName);

    if (target) {
        target.classList.add("active");
    } else {
        const story = $("#page-story");
        if (story) story.classList.add("active");
        pageName = "story";
    }

    $$("[data-page]").forEach(button => {
        button.classList.toggle(
            "active",
            button.dataset.page === pageName
        );
    });

    $$(".mobile-nav-item").forEach(button => {
        button.classList.toggle(
            "active",
            button.dataset.page === pageName
        );
    });

    state.currentPage = pageName;

    if (pageName === "calendar") renderCalendar();
    if (pageName === "tasks") renderTasks();
    if (pageName === "messages") renderMessenger();
    if (pageName === "dossiers") renderDossiers();
    if (pageName === "cases") renderCases();
    if (pageName === "companies") renderCompanies();
    if (pageName === "archive") renderArchive();
    if (pageName === "notifications") renderNotifications();

    saveGame();
}

