const fullStory = [];

function addDayTransitions() {
    let previousDate = null;

    scenes.forEach((item, index) => {
        if (previousDate && item.date !== previousDate) {
            const nextDate = item.date;

            fullStory.push({
                type: "dayEnd",
                date: previousDate,
                nextDate,
                title: "День завершён",
                subtitle: "До следующего дня"
            });
        }

        fullStory.push(item);
        previousDate = item.date;
    });

    fullStory.push({
        type: "final",
        date: "2026-10-30",
        nextDate: "2026-10-31"
    });
}

