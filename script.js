function formatDate(dateString) {
    const date = new Date(dateString + "T12:00:00");

    const day = String(date.getDate()).padStart(2, "0");
    const month = MONTH_NAMES[date.getMonth()].toLowerCase();

    return `${day} ${month}`;
}

function getCurrentScene() {
    return fullStory[
        Math.min(state.sceneIndex, fullStory.length - 1)
    ];
}

function getScenesForDate(date) {
    return scenes.filter(item => item.date === date);
}

function getUniqueDates() {
    return [...new Set(scenes.map(item => item.date))];
}

