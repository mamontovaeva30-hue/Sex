function getChatMessages(chatId) {
    if (!state.chats[chatId]) {
        state.chats[chatId] = [
            ...(contacts[chatId]?.messages || [])
        ];
    }

    return state.chats[chatId];
}

function renderChatContacts() {
    const container = $("#chat-contacts");

    if (!container) return;

    container.replaceChildren();

    Object.entries(contacts).forEach(([id, person]) => {
        const button = document.createElement("button");
        button.className = "chat-contact";

        if (state.activeChat === id) {
            button.classList.add("active");
        }

        const avatar = document.createElement("span");
        avatar.className = "chat-avatar";
        avatar.textContent = person.initials;

        const info = document.createElement("span");
        info.className = "chat-contact-info";

        const name = document.createElement("span");
        name.className = "chat-contact-name";
        name.textContent = person.name;

        const preview = document.createElement("span");
        preview.className = "chat-contact-preview";

        const messages = getChatMessages(id);
        const lastMessage = messages[messages.length - 1];

        preview.textContent = lastMessage
            ? lastMessage.text
            : "Нет сообщений";

        info.append(name, preview);
        button.append(avatar, info);

        button.addEventListener("click", () => {
            state.activeChat = id;
            renderMessenger();
            saveGame();
        });

        container.appendChild(button);
    });
}

function renderMessenger() {
    renderChatContacts();

    const person = contacts[state.activeChat];

    if (!person) return;

    const name = $("#chat-name");
    const container = $("#chat-messages");

    if (name) {
        name.textContent = person.name;
    }

    if (!container) return;

    container.replaceChildren();

    getChatMessages(state.activeChat).forEach(message => {
        const bubble = document.createElement("div");

        bubble.className = "chat-message " +
            (message.incoming ? "incoming" : "outgoing");

        const text = document.createElement("div");
        text.textContent = message.text;

        const time = document.createElement("div");
        time.className = "chat-message-time";
        time.textContent = message.time || "Сейчас";

        bubble.append(text, time);
        container.appendChild(bubble);
    });

    container.scrollTop = container.scrollHeight;
}

function sendMessage() {
    const input = $("#chat-input");

    if (!input) return;

    const value = input.value.trim();

    if (!value) {
        toast("Напиши сообщение.");
        return;
    }

    const chatId = state.activeChat;

    const messages = getChatMessages(chatId);

    messages.push({
        incoming: false,
        text: value,
        time: getClockTime()
    });

    input.value = "";

    const answerPool = replies[chatId] || [
        "Сообщение получено."
    ];

    const answer = answerPool[
        Math.floor(Math.random() * answerPool.length)
    ];

    messages.push({
        incoming: true,
        text: answer,
        time: getClockTime()
    });

    renderMessenger();
    saveGame();
}

function getClockTime() {
    const now = new Date();

    return (
        String(now.getHours()).padStart(2, "0") +
        ":" +
        String(now.getMinutes()).padStart(2, "0")
    );
}

function simulateCall() {
    const person = contacts[state.activeChat];

    if (!person) return;

    toast("Связь устанавливается…");

    const messages = getChatMessages(state.activeChat);

    messages.push({
        incoming: true,
        text: "Пропущенный вызов. Перезвоните позже.",
        time: getClockTime()
    });

    renderMessenger();
    saveGame();
}

